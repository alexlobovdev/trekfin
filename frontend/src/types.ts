export type Person = { id: number; name: string };
export type User = Person & { email: string; must_change_password: boolean };
export type Kind = "expense" | "income";
export type CategoryMode = "limit" | "payment";
export type Category = {
  id: number;
  name: string;
  kind: Kind;
  mode: CategoryMode;
  icon: string;
  color: string;
  active: boolean;
};
export type CategoryProgress = {
  id: number;
  name: string;
  kind: Kind;
  mode: CategoryMode;
  color: string;
  icon: string;
  planned_cents: number;
  actual_cents: number;
  left_cents: number;
  over_cents: number;
};
export type Entry = {
  id: number;
  title: string;
  category_id: number;
  category: Category;
  author_id: number | null;
  author: Person | null;
  created_by: number;
  kind: Kind;
  state: "actual" | "planned";
  amount_cents: number;
  paid_cents: number;
  date: string;
  date_confirmed: boolean;
  note: string | null;
  plan_id: number | null;
  source_key: string | null;
  debt_id: number | null;
  savings_goal_id: number | null;
  debt?: { id: number; title: string } | null;
};
export type Recurring = {
  id: number;
  title: string;
  category_id: number;
  author_id: number | null;
  amount_cents: number;
  summer_cents: number | null;
  day: number;
  kind: Kind;
  active: boolean;
  note: string | null;
};
export type MonthPlan = {
  month: string;
  opening_cents: number;
  note: string | null;
};
export type Month = {
  month: string;
  plan: MonthPlan | null;
  entries: Entry[];
  categories: CategoryProgress[];
  totals: {
    planned_income: number;
    planned_expense: number;
    income: number;
    expense: number;
    balance: number;
    planned_balance: number;
    forecast: number;
    savings: number;
  };
  by_author: (Person & { income: number; expense: number })[];
};
export type ImportReport = {
  sheets: string[];
  months: {
    month: string;
    income_cents: number;
    expense_cents: number;
    opening_cents: number;
    remaining_cents: number;
    source_remaining_cents: number;
  }[];
  notes: string[];
};
export type Bootstrap = {
  users: Person[];
  categories: Category[];
  recurrings: Recurring[];
  months: MonthPlan[];
  push_key: string;
  import: ImportReport | null;
  debts: Debt[];
  savings: SavingsGoal[];
};
export type Debt = {
  id: number;
  title: string;
  amount_cents: number;
  paid_cents: number;
  note: string;
  type: "loan" | "debt" | "internal";
  creditor: string | null;
  author_id: number;
  initial_paid_cents: number;
  monthly_payment_cents: number;
  payment_day: number | null;
  due_date: string | null;
  archived: boolean;
  repayments: MoneyRecord[];
  entries: Entry[];
};
export type MoneyRecord = {
  id: number;
  amount_cents: number;
  date: string | null;
  author_id: number | null;
  created_by: number;
  note: string | null;
  kind?: Kind;
  plan_id?: number | null;
};
export type SavingsGoal = {
  id: number;
  title: string;
  target_cents: number;
  opening_cents: number;
  saved_cents: number;
  color: string;
  icon: string;
  due_date: string | null;
  note: string | null;
  archived: boolean;
  movements: MoneyRecord[];
};
export type Insight = {
  title: string;
  body: string;
  source: string;
  link: string;
  section: string;
  updated: string | null;
  live: boolean;
  rates: { date: string; values: Record<string, number> } | null;
};
